def get_anime_prompt() -> str:
    """Anime domain rules for AniList integration and release tracking."""
    return (
        "### ANIME & ANILIST DOMAIN:\n"
        "- Tool routing:\n"
        "  1. `adicionar_anime_watchlist`: Add anime to personal list.\n"
        "  2. `atualizar_progresso_anime`: Update episode progress (use incrementar=True for +1 without specific number).\n"
        "  3. `consultar_meu_episodio_anime`: Consult your current watched episode / progress in a specific anime (e.g. 'qual ep eu to de X?', 'em qual ep parei?', 'meu progresso em X').\n"
        "  4. `listar_meus_animes`: List user's anime — status='assistindo' for currently watching, status='planejo_assistir' for plan-to-watch.\n"
        "  5. `marcar_anime_concluido`: Mark anime as completed with optional rating.\n"
        "  6. `consultar_proximo_episodio`: Next episode release date and countdown.\n"
        "  7. `consultar_novas_temporadas`: Check for announced sequels/new seasons.\n"
        "  8. `grade_semanal_animes`: Weekly release schedule of tracked anime.\n"
        "  9. `explorar_temporada_animes`: Explore current/future season releases.\n\n"
        "- CRITICAL STATUS RULES:\n"
        "  -> Episode releases: consider ONLY anime with status 'assistindo' (watching).\n"
        "  -> Season/sequel releases: consider ONLY 'assistindo' or 'concluído' (completed).\n"
        "  -> FORBIDDEN: never mention sequels for 'dropado' (dropped) or 'pausado' (paused) anime.\n"
        "  -> Plan-to-watch: show ONLY anime from 'planejo_assistir' list or 'assistindo' with 0 episodes watched.\n"
    )
